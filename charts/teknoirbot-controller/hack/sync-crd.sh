#!/usr/bin/env bash
# Refreshes crds/teknoir.org_teknoirbots.yaml from the controller repo's generated CRD and adds the
# ArgoCD sync option Prune=false,Delete=false (the Application prunes, and pruning a CRD deletes every bot).
# Idempotent: a second run gives the same bytes.
#   charts/teknoirbot-controller/hack/sync-crd.sh <controller-repo-dir>
set -euo pipefail
src_dir="${1:?usage: sync-crd.sh <teknoirbot-controller repo dir>}"
src="${src_dir}/config/crd/bases/teknoir.org_teknoirbots.yaml"
[[ -f "$src" ]] || { echo "missing $src" >&2; exit 2; }
dst="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)/crds/teknoir.org_teknoirbots.yaml"
tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT
python3 -I - "$src" "$tmp" <<'PY'
import sys

src, out = sys.argv[1], sys.argv[2]
lines = open(src).read().split("\n")
res = []
done = False
for i, line in enumerate(lines):
    if line == "---" and not res:
        continue  # generated leading document marker; the header comment replaces it
    if line == "  annotations:" and not done and res and res[-1] == "metadata:":
        res.append(line)
        res.append("    argocd.argoproj.io/sync-options: Prune=false,Delete=false")
        done = True
        continue
    res.append(line)
    if line == "metadata:" and not done and lines[i + 1] != "  annotations:":
        # no annotations block: add one
        res.append("  annotations:")
        res.append("    argocd.argoproj.io/sync-options: Prune=false,Delete=false")
        done = True
if not done:
    sys.exit("could not add the sync-options annotation")
header = [
    "---",
    "# Generated by teknoirbot-controller (make manifests); refreshed with charts/teknoirbot-controller/hack/sync-crd.sh.",
    "# Do not edit. Prune=false,Delete=false: pruning a CRD deletes every TeknoirBot.",
]
open(out, "w").write("\n".join(header + res))
PY
mv "$tmp" "$dst"
trap - EXIT
echo "wrote $dst"
